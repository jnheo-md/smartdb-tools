def _require_auth() -> None:
    """Raise if not logged in."""
    if not api_client.is_logged_in():
        raise api_client.APIError(
            "Not logged in. Please run 'smartdb login' in the CLI first to authenticate, "
            "then restart this MCP server.",
            status_code=401,
        )


def _fetch_anon_mapping(
    hospital_code: str, hidx: int, patient_ids: list[int],
) -> tuple[dict[int, dict] | None, str | None]:
    """Fetch de-anonymized patient identifiers (chart#, name) for patient IDs.

    Uses /anon/batch which allows any logged-in user with hospital access.
    Returns (mapping_dict, error_message). mapping_dict maps
    patient_id -> {"chart_no": str, "patient_name": str}.
    """
    if not patient_ids:
        return None, None

    try:
        result = api_client.post("/anon/batch", json_body={
            "hospital": hospital_code,
            "patient_ids": [int(pid) for pid in patient_ids[:5000]],
        })
    except api_client.APIError as exc:
        if exc.status_code == 404:
            return None, None
        return None, str(exc)

    if not result:
        return None, None

    mapping: dict[int, dict] = {}
    for row in result:
        pid = row.get("patient_id")
        if pid is not None:
            mapping[int(pid)] = {
                "chart_no": str(row.get("chart_no", "")),
                "patient_name": str(row.get("patient_name", "")),
            }

    return (mapping if mapping else None), None


def _format_table(rows: list[dict], columns: list[str], max_rows: int = 50) -> str:
    """Format rows as a simple text table."""
    if not rows:
        return "(no data)"
    lines = [" | ".join(columns)]
    lines.append("-+-".join("-" * max(len(c), 8) for c in columns))
    for row in rows[:max_rows]:
        vals = [str(row.get(c, "")) for c in columns]
        lines.append(" | ".join(vals))
    if len(rows) > max_rows:
        lines.append(f"... ({len(rows) - max_rows} more rows)")
    return "\n".join(lines)


def _dedupe(items: list[str]) -> list[str]:
    """Return a list with duplicates removed while preserving order."""
    seen: set[str] = set()
    result: list[str] = []
    for item in items:
        if item and item not in seen:
            seen.add(item)
            result.append(item)
    return result


def _extract_filter_variables(filter_list: list[dict]) -> list[str]:
    """Extract variable names referenced by structured filters."""
    variables: list[str] = []
    for filt in filter_list:
        variable = filt.get("variable")
        if isinstance(variable, str) and variable:
            variables.append(variable)
    return _dedupe(variables)


def _format_dangerous_variable_block(warnings: list[dict], action: str) -> str:
    """Format a hard-stop response for known dangerous variables."""
    lines = [
        f"STOP — {action} was not run because unsafe variables were requested.",
        "",
        "Dangerous variables:",
    ]
    for warning in warnings:
        lines.append(f"  - {warning['variable']}: {warning['reason']}")
        if warning.get("safe"):
            lines.append(f"    Use '{warning['safe']}' instead, or use {warning['tool']}.")
        elif warning.get("tool"):
            lines.append(f"    Use {warning['tool']} instead.")
    lines.extend([
        "",
        "Ask the user before substituting variables or changing outcome/NIHSS handling.",
    ])
    return "\n".join(lines)


def _safe_api_error(exc: api_client.APIError) -> str:
    """Return a compact API error string for validation reports."""
    if exc.status_code:
        return f"HTTP {exc.status_code}: {exc}"
    return str(exc)


def _get_table_layout_keys(
    hospital_code: str,
    table_name: str,
    layout_cache: dict[tuple[str, str], tuple[set[str], str, str | None]],
) -> tuple[set[str], str, str | None]:
    """Return variables present in a hospital table layout.

    Prefer form_layout sections. Fall back to table-vars only when a table has
    no form layout endpoint data.
    """
    cache_key = (hospital_code, table_name)
    if cache_key in layout_cache:
        return layout_cache[cache_key]

    keys: set[str] = set()
    source = "form_layout"
    error: str | None = None

    try:
        sections = api_client.get(f"/schema/sections/{hospital_code}/{table_name}")
    except api_client.APIError as exc:
        sections = []
        error = _safe_api_error(exc)

    if sections:
        for order in sorted({section["section_order"] for section in sections}):
            try:
                section_data = api_client.get(
                    f"/schema/section-vars/{hospital_code}/{table_name}/{order}"
                )
            except api_client.APIError as exc:
                error = _safe_api_error(exc)
                continue
            for subsection in section_data.get("subsections", []):
                for variable in subsection.get("variables", []):
                    key = variable.get("key")
                    if key:
                        keys.add(key)
    else:
        source = "table_vars"
        try:
            table_vars = api_client.get(f"/schema/table-vars/{hospital_code}/{table_name}")
            for variable in table_vars:
                key = variable.get("key")
                if key:
                    keys.add(key)
            error = None
        except api_client.APIError as exc:
            error = _safe_api_error(exc)

    result = (keys, source, error)
    layout_cache[cache_key] = result
    return result


def _count_records(hospital_code: str, filters: list[dict]) -> tuple[int | None, str | None]:
    """Count records matching filters, returning an error instead of raising."""
    try:
        result = api_client.post(
            "/query/count",
            json_body={"hospital": hospital_code, "filters": filters},
        )
        return int(result.get("count", 0)), None
    except api_client.APIError as exc:
        return None, _safe_api_error(exc)


def _count_non_null_records(
    hospital_code: str,
    variable_name: str,
    filters: list[dict],
) -> tuple[int | None, str | None]:
    """Count records where a variable is non-null under the requested filters."""
    non_null_filters = list(filters) + [
        {"variable": variable_name, "operator": "IS NOT NULL"}
    ]
    return _count_records(hospital_code, non_null_filters)


def _search_variable_candidates(hospital_code: str, query: str, limit: int = 5) -> list[dict]:
    """Search variable candidates, suppressing API failures in validation."""
    try:
        result = api_client.get(
            f"/schema/search/{hospital_code}",
            params={"q": query, "limit": limit},
        )
        return result if isinstance(result, list) else []
    except api_client.APIError:
        return []


def _variable_signature(variable_info: dict) -> str:
    """Signature used to detect cross-hospital format/encoding differences."""
    value_map = variable_info.get("value_map") or {}
    normalized_value_map = {
        str(key): str(value) for key, value in sorted(value_map.items(), key=lambda item: str(item[0]))
    }
    payload = {
        "type": str(variable_info.get("type", "")),
        "type_label": str(variable_info.get("type_label", "")),
        "options": str(variable_info.get("options", "")),
        "value_map": normalized_value_map,
    }
    return json.dumps(payload, sort_keys=True, ensure_ascii=False)


def _format_variable_format(variable_info: dict) -> str:
    """Human-readable compact description of a variable's format."""
    type_label = str(variable_info.get("type_label", "") or "?")
    value_map = variable_info.get("value_map") or {}
    if value_map:
        items = [
            f"{key}={value}"
            for key, value in sorted(value_map.items(), key=lambda item: str(item[0]))[:8]
        ]
        suffix = ", ..." if len(value_map) > 8 else ""
        return f"{type_label}; values: {', '.join(items)}{suffix}"
    options = str(variable_info.get("options", "") or "").strip()
    if options:
        compact_options = " ".join(options.split())
        if len(compact_options) > 160:
            compact_options = compact_options[:157] + "..."
        return f"{type_label}; options: {compact_options}"
    return type_label


def _validate_variable_selection_impl(
    hospital_codes: list[str],
    variables: list[str],
    filter_list: list[dict],
    require_data: bool,
    search_missing: bool = True,
) -> dict:
    """Validate variable layout presence, data availability, and formats."""
    requested_variables = _dedupe(variables)
    filter_variables = _extract_filter_variables(filter_list)
    variables_to_check = _dedupe(requested_variables + filter_variables)
    layout_cache: dict[tuple[str, str], tuple[set[str], str, str | None]] = {}

    validation: dict = {
        "ok": True,
        "requires_user_decision": False,
        "hospital_codes": hospital_codes,
        "variables": requested_variables,
        "filter_variables": filter_variables,
        "require_data": require_data,
        "hospitals": [],
        "format_differences": [],
        "issues": [],
    }

    format_groups: dict[str, dict[str, list[dict]]] = {
        variable: {} for variable in requested_variables
    }

    for hospital_code in hospital_codes:
        hospital_report: dict = {
            "hospital": hospital_code,
            "total_count": None,
            "total_count_error": None,
            "variables": [],
        }

        total_count, total_error = _count_records(hospital_code, filter_list)
        hospital_report["total_count"] = total_count
        hospital_report["total_count_error"] = total_error
        if require_data and total_error:
            validation["issues"].append({
                "hospital": hospital_code,
                "variable": "(filters)",
                "severity": "BLOCK",
                "reason": f"Could not count records with current filters: {total_error}",
            })
        elif require_data and total_count == 0:
            validation["issues"].append({
                "hospital": hospital_code,
                "variable": "(filters)",
                "severity": "BLOCK",
                "reason": "No records match the current filters.",
            })

        for variable_name in variables_to_check:
            role_parts = []
            if variable_name in requested_variables:
                role_parts.append("column")
            if variable_name in filter_variables:
                role_parts.append("filter")
            variable_report: dict = {
                "name": variable_name,
                "role": "+".join(role_parts),
                "exists": False,
                "in_layout": False,
                "table": "",
                "type_label": "",
                "format": "",
                "non_null_count": None,
                "non_null_error": None,
                "suggestions": [],
                "issues": [],
            }

            try:
                variable_info = api_client.get(
                    f"/schema/variable/{hospital_code}/{variable_name}"
                )
            except api_client.APIError as exc:
                issue = f"Variable is not registered for this hospital: {_safe_api_error(exc)}"
                variable_report["issues"].append(issue)
                if search_missing:
                    variable_report["suggestions"] = _search_variable_candidates(
                        hospital_code, variable_name
                    )
                validation["issues"].append({
                    "hospital": hospital_code,
                    "variable": variable_name,
                    "severity": "BLOCK",
                    "reason": issue,
                })
                hospital_report["variables"].append(variable_report)
                continue

            variable_report["exists"] = True
            table_name = str(variable_info.get("table", "") or "")
            variable_report["table"] = table_name
            variable_report["type_label"] = str(variable_info.get("type_label", "") or "")
            variable_report["format"] = _format_variable_format(variable_info)

            layout_keys, layout_source, layout_error = _get_table_layout_keys(
                hospital_code, table_name, layout_cache
            )
            variable_report["layout_source"] = layout_source
            if layout_error and not layout_keys:
                issue = f"Could not verify table layout for {table_name}: {layout_error}"
                variable_report["issues"].append(issue)
                validation["issues"].append({
                    "hospital": hospital_code,
                    "variable": variable_name,
                    "severity": "BLOCK",
                    "reason": issue,
                })
            elif variable_name not in layout_keys:
                issue = (
                    f"Variable exists in schema table {table_name}, but is not present "
                    f"in the hospital's {layout_source} field list."
                )
                variable_report["issues"].append(issue)
                validation["issues"].append({
                    "hospital": hospital_code,
                    "variable": variable_name,
                    "severity": "BLOCK",
                    "reason": issue,
                })
            else:
                variable_report["in_layout"] = True

            if variable_name in requested_variables:
                non_null_count, non_null_error = _count_non_null_records(
                    hospital_code, variable_name, filter_list
                )
                variable_report["non_null_count"] = non_null_count
                variable_report["non_null_error"] = non_null_error
                if non_null_error:
                    issue = f"Could not verify non-null data count: {non_null_error}"
                    variable_report["issues"].append(issue)
                    validation["issues"].append({
                        "hospital": hospital_code,
                        "variable": variable_name,
                        "severity": "BLOCK" if require_data else "WARN",
                        "reason": issue,
                    })
                elif require_data and non_null_count == 0:
                    issue = "Column has 0 non-null records under the current filters."
                    variable_report["issues"].append(issue)
                    validation["issues"].append({
                        "hospital": hospital_code,
                        "variable": variable_name,
                        "severity": "BLOCK",
                        "reason": issue,
                    })

                signature = _variable_signature(variable_info)
                format_groups[variable_name].setdefault(signature, []).append({
                    "hospital": hospital_code,
                    "table": table_name,
                    "format": variable_report["format"],
                })

            hospital_report["variables"].append(variable_report)

        validation["hospitals"].append(hospital_report)

    if len(hospital_codes) > 1:
        for variable_name, groups in format_groups.items():
            if len(groups) <= 1:
                continue
            validation["format_differences"].append({
                "variable": variable_name,
                "groups": list(groups.values()),
            })
            validation["issues"].append({
                "hospital": "(multiple)",
                "variable": variable_name,
                "severity": "BLOCK",
                "reason": "Variable type/options/value encoding differ across hospitals.",
            })

    blocking_issues = [
        issue for issue in validation["issues"] if issue.get("severity") == "BLOCK"
    ]
    validation["ok"] = not blocking_issues
    validation["requires_user_decision"] = bool(blocking_issues)
    return validation


def _format_validation_report(validation: dict) -> str:
    """Format validation results for MCP users and guardrail responses."""
    lines = [
        "Variable selection preflight",
        f"Hospitals checked: {', '.join(validation['hospital_codes'])}",
        f"Requested columns: {', '.join(validation['variables']) if validation['variables'] else '(none)'}",
    ]
    if validation["filter_variables"]:
        lines.append(f"Filter variables checked: {', '.join(validation['filter_variables'])}")
    lines.append("")

    for hospital in validation["hospitals"]:
        count = hospital.get("total_count")
        count_text = "unknown" if count is None else f"{count:,}"
        if hospital.get("total_count_error"):
            count_text = f"error ({hospital['total_count_error']})"
        lines.append(f"{hospital['hospital']} — records matching filters: {count_text}")

        for variable in hospital["variables"]:
            status = "OK" if variable["exists"] and variable["in_layout"] and not variable["issues"] else "CHECK"
            data_text = ""
            if variable["role"].startswith("column") or "+column" in variable["role"]:
                non_null = variable.get("non_null_count")
                if non_null is not None:
                    data_text = f"; non-null={non_null:,}"
                elif variable.get("non_null_error"):
                    data_text = f"; non-null error={variable['non_null_error']}"
            if variable["exists"]:
                lines.append(
                    f"  [{status}] {variable['name']} ({variable['role']}): "
                    f"table={variable['table']}; layout={variable.get('layout_source', '?')}; "
                    f"{variable['format']}{data_text}"
                )
            else:
                lines.append(f"  [CHECK] {variable['name']} ({variable['role']}): missing")

            for issue in variable["issues"]:
                lines.append(f"      - {issue}")
            if variable["suggestions"]:
                suggestions = []
                for suggestion in variable["suggestions"][:5]:
                    suggestions.append(
                        f"{suggestion.get('key', '?')}[{suggestion.get('table', '?')}: "
                        f"{suggestion.get('type_label', '?')}]"
                    )
                lines.append(f"      Suggestions: {', '.join(suggestions)}")
        lines.append("")

    if validation["format_differences"]:
        lines.append("Cross-hospital format differences:")
        for difference in validation["format_differences"]:
            lines.append(f"  - {difference['variable']}:")
            for group in difference["groups"]:
                hospitals = ", ".join(item["hospital"] for item in group)
                sample = group[0]
                lines.append(
                    f"      {hospitals}: table={sample['table']}; {sample['format']}"
                )
        lines.append("")

    if validation["requires_user_decision"]:
        lines.extend([
            "STOP — user decision required before export/final column selection.",
            "Ask the user how to handle missing, empty, or differently encoded fields:",
            "  1. drop the affected hospital/column",
            "  2. map a hospital-specific alternative variable",
            "  3. normalize value encodings into a shared output column",
            "  4. keep hospital-specific columns with explicit source field names",
            "  5. proceed with empty columns only after explicit confirmation",
        ])
    elif not validation["require_data"]:
        lines.append("Preflight passed. Variables exist in each hospital layout; zero-data columns were not treated as blockers.")
    else:
        lines.append("Preflight passed. Variables exist in each hospital layout and requested columns have data.")

    return "\n".join(lines).rstrip()


def _field_reference_path() -> Path:
    return REFERENCE_CACHE_DIR / FIELD_REFERENCE_FILENAME


def _load_field_reference() -> tuple[dict | None, str | None]:
    path = _field_reference_path()
    if not path.exists():
        return None, f"No local field reference cache found at {path}."
    try:
        return json.loads(path.read_text(encoding="utf-8")), None
    except (json.JSONDecodeError, OSError) as exc:
        return None, f"Could not read field reference cache at {path}: {exc}"


def _validate_field_reference_payload(payload: dict) -> str | None:
    if not isinstance(payload, dict):
        return "Reference payload is not a JSON object."
    metadata = payload.get("metadata")
    if not isinstance(metadata, dict):
        return "Reference payload is missing metadata."
    if metadata.get("schema_version") != 1:
        return f"Unsupported reference schema_version: {metadata.get('schema_version')}"
    if not isinstance(payload.get("field_index"), dict):
        return "Reference payload is missing field_index."
    if not isinstance(payload.get("differences"), list):
        return "Reference payload is missing differences."
    return None


def _save_field_reference(payload: dict) -> Path:
    validation_error = _validate_field_reference_payload(payload)
    if validation_error:
        raise ValueError(validation_error)
    REFERENCE_CACHE_DIR.mkdir(parents=True, exist_ok=True)
    path = _field_reference_path()
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def _download_field_reference(source_url: str) -> dict:
    parsed = urlparse(source_url)
    if parsed.scheme != "https":
        raise api_client.APIError("Field reference URL must use https.")
    if (
        parsed.netloc != "raw.githubusercontent.com"
        and os.environ.get("SMARTDB_ALLOW_CUSTOM_REFERENCE_URL") != "1"
    ):
        raise api_client.APIError(
            "Custom field reference URLs are disabled by default. "
            "Use raw.githubusercontent.com or set SMARTDB_ALLOW_CUSTOM_REFERENCE_URL=1."
        )
    with httpx.Client(timeout=60.0) as client:
        response = client.get(source_url, headers={"Accept": "application/json"})
    if response.status_code >= 400:
        raise api_client.APIError(
            f"Could not download field reference cache from {source_url} "
            f"(HTTP {response.status_code}).",
            status_code=response.status_code,
        )
    payload = response.json()
    validation_error = _validate_field_reference_payload(payload)
    if validation_error:
        raise api_client.APIError(
            f"Downloaded field reference cache is invalid: {validation_error}"
        )
    return payload


def _format_reference_metadata(payload: dict, local_path: Path | None = None) -> list[str]:
    metadata = payload.get("metadata", {})
    lines = [
        f"Schema version: {metadata.get('schema_version', '?')}",
        f"Generated at: {metadata.get('generated_at', '?')}",
        f"Privacy: {metadata.get('privacy', '?')}",
        f"Data checks: {metadata.get('data_checks', '?')}",
        f"Hospitals: {metadata.get('hospital_count', '?')}",
        f"Fields: {metadata.get('field_count', '?')}",
        f"Differences: {metadata.get('difference_count', '?')}",
    ]
    if local_path:
        lines.append(f"Local cache: {local_path}")
    if metadata.get("reference_url"):
        lines.append(f"Reference URL: {metadata['reference_url']}")
    return lines


def _matches_hospital_filter(record_hospitals: list[str], hospital_codes: list[str] | None) -> bool:
    if not hospital_codes:
        return True
    wanted = {code.upper() for code in hospital_codes}
    return bool(wanted.intersection({code.upper() for code in record_hospitals}))


