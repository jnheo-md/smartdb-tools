@mcp.tool()
async def query_data(
    hospital_code: str,
    variables: list[str],
    filters: str = "",
    limit: int = 100,
    include_patient_id: bool = False,
) -> str:
    """Query patient data from the stroke registry.

    Returns tabular data for the requested variables.

    NOTE: Do NOT use this tool for mRS outcome data. Use get_followup_mrs() instead,
    which queries the authoritative cohort table (db_5) with death imputation.

    Args:
        hospital_code: Hospital code (e.g., 'YSU') or hidx
        variables: List of variable names to retrieve
                   (e.g., ['pt_sex', 'pt_age', 'hypertension'])
        filters: JSON string of filters, e.g.,
                 '[{"variable": "stroke_type", "operator": "=", "value": "LAA"}]'
                 Supported operators: =, !=, IN, NOT IN, >, <, >=, <=,
                 IS NULL, IS NOT NULL, LIKE
        limit: Max rows to return (default 100, max 5000)
        include_patient_id: If True, include original patient identifiers
                 (chart number, patient name) from the anonymization table.
                 Only works for anonymized tables and the user's own hospital.
    """
    _require_auth()
    if not variables:
        return "Please provide at least one variable to query."
    filter_list = _parse_filters(filters)

    dangerous_warnings = variable_safety.check_dangerous_variables(
        _dedupe(variables + _extract_filter_variables(filter_list)),
        hospital_code,
    )
    if dangerous_warnings:
        return _format_dangerous_variable_block(dangerous_warnings, "query")

    validation = _validate_variable_selection_impl(
        hospital_codes=[hospital_code],
        variables=variables,
        filter_list=filter_list,
        require_data=False,
    )
    if not validation["ok"]:
        return (
            _format_validation_report(validation)
            + "\n\nQuery was NOT run. Ask the user how to handle these fields first."
        )

    body = {
        "hospital": hospital_code,
        "variables": variables,
        "filters": filter_list,
        "limit": max(1, min(limit, 5000)),
    }
    result = api_client.post("/query/data", json_body=body)
    columns = result["columns"]
    rows = result["rows"]
    summary = result.get("summary", {})

    # De-anonymization: merge chart_no and patient_name into results
    anon_note = None
    if include_patient_id and rows:
        patient_ids = [r.get("patient_id") for r in rows if r.get("patient_id")]
        hidx = result.get("hidx")
        if patient_ids and hidx:
            anon_map, anon_err = _fetch_anon_mapping(hospital_code, hidx, patient_ids)
            if anon_err:
                anon_note = anon_err
            elif anon_map:
                columns = ["chart_no", "patient_name"] + columns
                for row in rows:
                    pid = row.get("patient_id")
                    anon = anon_map.get(int(pid)) if pid else None
                    row["chart_no"] = anon["chart_no"] if anon else ""
                    row["patient_name"] = anon["patient_name"] if anon else ""
            else:
                anon_note = "No anonymization data found (table may not be anonymized)."

    lines = []

    lines.extend([
        f"Hospital: {result.get('hospital', hospital_code)} (hidx={result.get('hidx', '')})",
        f"Variables: {', '.join(variables)}",
        "Preflight: table layout verified before query",
        f"Rows: {result['row_count']} (limit: {result['limit']})",
        "",
        _format_table(rows, columns),
    ])

    if anon_note:
        lines.append(f"\nNote: {anon_note}")

    if summary:
        lines.append("\n--- Summary ---")
        for col, stats in summary.items():
            if stats.get("type") == "numeric":
                lines.append(
                    f"  {col}: n={stats['n']}, mean={stats['mean']:.2f}, "
                    f"median={stats['median']:.2f}, min={stats['min']}, max={stats['max']}"
                )
            elif stats.get("type") == "categorical":
                top = ", ".join(f"{t['value']}={t['count']}" for t in stats.get("top", []))
                lines.append(f"  {col}: n={stats['n']}, nulls={stats['nulls']}, unique={stats['unique']}, top: {top}")

    return "\n".join(lines)


