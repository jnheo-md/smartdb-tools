@mcp.tool()
async def lookup_field_reference(
    variable_name: str,
    hospital_codes: list[str] | None = None,
    refresh_if_missing: bool = True,
) -> str:
    """Look up known cross-hospital differences for a variable.

    Use this before selecting raw export columns. This is a reference cache
    only; still run validate_variable_selection() before query_data() or
    export_xlsx() because live data/layouts may have changed.

    Args:
        variable_name: Field key to look up. Exact match preferred; substring
            matches are listed if exact match is not found.
        hospital_codes: Optional hospital filter, e.g. ['YSU', 'EWU'].
        refresh_if_missing: If True, download the GitHub cache when local cache is absent.
    """
    payload, error = _load_field_reference()
    if error and refresh_if_missing:
        try:
            payload = _download_field_reference(DEFAULT_FIELD_REFERENCE_URL)
            _save_field_reference(payload)
            error = None
        except Exception as exc:
            error = f"{error} Refresh failed: {exc}"
    if error or payload is None:
        return "\n".join([
            "Field reference cache is not available.",
            error or "",
            "Run refresh_field_reference_cache() after the GitHub artifact has been created.",
        ])

    field_index = payload.get("field_index", {})
    exact_key = variable_name if variable_name in field_index else None
    if exact_key is None:
        lower_name = variable_name.lower()
        for key in field_index:
            if key.lower() == lower_name:
                exact_key = key
                break

    if exact_key is None:
        matches = [
            key for key in sorted(field_index)
            if variable_name.lower() in key.lower()
        ][:20]
        if matches:
            return "\n".join([
                f"No exact field reference match for '{variable_name}'.",
                "Possible matches:",
                *[f"  - {match}" for match in matches],
            ])
        return f"No field reference match found for '{variable_name}'."

    entry = field_index[exact_key]
    hospital_filter = hospital_codes or []
    lines = [f"Field reference: {exact_key}"]
    lines.append(f"Generated at: {payload.get('metadata', {}).get('generated_at', '?')}")
    lines.append("")
    lines.append("Hospital fields:")

    hospitals = entry.get("hospitals", {})
    for hospital_code in sorted(hospitals):
        if hospital_filter and hospital_code.upper() not in {code.upper() for code in hospital_filter}:
            continue
        record = hospitals[hospital_code]
        value_map = record.get("value_map") or {}
        if value_map:
            values = ", ".join(
                f"{key}={value}"
                for key, value in list(value_map.items())[:8]
            )
            if len(value_map) > 8:
                values += ", ..."
        else:
            values = "(no value map)"
        lines.append(
            f"  {hospital_code}: table={record.get('table', '')}; "
            f"type={record.get('type_label', '')}; "
            f"data={record.get('non_null_records_bucket', 'unknown')}; values={values}"
        )

    differences = [
        difference for difference in entry.get("differences", [])
        if _matches_hospital_filter(
            difference.get("present_hospitals", []) + difference.get("missing_hospitals", []),
            hospital_filter,
        )
    ]
    if differences:
        lines.append("")
        lines.append("Known differences requiring review:")
        for difference in differences:
            lines.append(
                f"  - {difference.get('issue_type')}: {difference.get('summary')} "
                f"(present: {', '.join(difference.get('present_hospitals', []))}; "
                f"missing: {', '.join(difference.get('missing_hospitals', [])) or 'none'})"
            )
    else:
        lines.append("")
        lines.append("No known differences for the selected hospitals in the cached reference.")

    lines.append("")
    lines.append("Still run validate_variable_selection() before final query/export.")
    return "\n".join(lines)


@mcp.tool()
async def list_field_reference_differences(
    variable_name: str = "",
    issue_type: str = "",
    hospital_codes: list[str] | None = None,
    limit: int = 50,
    refresh_if_missing: bool = True,
) -> str:
    """List cached cross-hospital field differences.

    Args:
        variable_name: Optional exact/substring field filter.
        issue_type: Optional issue filter, e.g. missing_column,
            value_encoding_differs, data_presence_differs.
        hospital_codes: Optional hospital filter.
        limit: Max rows to return.
        refresh_if_missing: If True, download the GitHub cache when local cache is absent.
    """
    payload, error = _load_field_reference()
    if error and refresh_if_missing:
        try:
            payload = _download_field_reference(DEFAULT_FIELD_REFERENCE_URL)
            _save_field_reference(payload)
            error = None
        except Exception as exc:
            error = f"{error} Refresh failed: {exc}"
    if error or payload is None:
        return "\n".join([
            "Field reference cache is not available.",
            error or "",
            "Run refresh_field_reference_cache() after the GitHub artifact has been created.",
        ])

    lower_variable = variable_name.lower().strip()
    lower_issue = issue_type.lower().strip()
    hospital_filter = hospital_codes or []
    rows = []
    for difference in payload.get("differences", []):
        field_key = str(difference.get("field_key", ""))
        current_issue = str(difference.get("issue_type", ""))
        if lower_variable and lower_variable not in field_key.lower():
            continue
        if lower_issue and lower_issue != current_issue.lower():
            continue
        if not _matches_hospital_filter(
            difference.get("present_hospitals", []) + difference.get("missing_hospitals", []),
            hospital_filter,
        ):
            continue
        rows.append(difference)

    lines = [
        "Cached field differences",
        f"Generated at: {payload.get('metadata', {}).get('generated_at', '?')}",
        f"Matches: {len(rows)}",
        "",
    ]
    for difference in rows[: max(1, min(limit, 200))]:
        lines.append(
            f"- {difference.get('field_key')} [{difference.get('issue_type')}]: "
            f"{difference.get('summary')}"
        )
        missing = ", ".join(difference.get("missing_hospitals", []))
        if missing:
            lines.append(f"  missing: {missing}")
    if len(rows) > limit:
        lines.append(f"... ({len(rows) - limit} more)")
    lines.append("")
    lines.append("Use lookup_field_reference(variable_name) for details, then validate live before export.")
    return "\n".join(lines)


@mcp.tool()
async def validate_variable_selection(
    hospital_codes: list[str],
    variables: list[str],
    filters: str = "",
    require_data: bool = True,
) -> str:
    """Validate raw query/export variables before final column selection.

    Use this before query_data() or export_xlsx(), especially for multi-hospital
    work. It validates each hospital independently instead of assuming that
    variables present in YSU exist or are encoded the same elsewhere.

    Checks performed:
      1. Each variable/filter field is registered for each hospital.
      2. The variable exists in that hospital's table layout/field list.
      3. Requested output columns have non-null data under the current filters.
      4. Multi-hospital selections have matching type/options/value encodings.

    If anything is missing, empty, or encoded differently, stop and ask the
    user how to map/drop/normalize the affected columns before exporting.

    Args:
        hospital_codes: Hospital codes to validate (e.g., ['YSU', 'EWU'])
        variables: Requested output columns
        filters: JSON string of filters (same format as query_data)
        require_data: If True, zero non-null records is a blocking issue
    """
    _require_auth()
    if not hospital_codes:
        return "Please provide at least one hospital code to validate."
    if not variables:
        return "Please provide at least one requested output variable to validate."

    filter_list = _parse_filters(filters)
    dangerous_warnings = variable_safety.check_dangerous_variables(
        _dedupe(variables + _extract_filter_variables(filter_list)),
        "",
    )
    if dangerous_warnings:
        return _format_dangerous_variable_block(dangerous_warnings, "variable validation")

    validation = _validate_variable_selection_impl(
        hospital_codes=_dedupe(hospital_codes),
        variables=variables,
        filter_list=filter_list,
        require_data=require_data,
    )
    return _format_validation_report(validation)


